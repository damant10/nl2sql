import re
from typing import Tuple
from pydantic import BaseModel, Field
from langchain_ollama import ChatOllama
from langchain_core.prompts import ChatPromptTemplate
from langchain_core.output_parsers import StrOutputParser, JsonOutputParser

from schema import schema_customer, schema_deposit, schema_loan
from logger_config import setup_logger

logger = setup_logger("nlp2sql")

DISALLOWED_KEYWORDS = {
    "INSERT", "UPDATE", "DELETE", "DROP", "ALTER",
    "TRUNCATE", "REPLACE", "CREATE", "GRANT", "REVOKE"
}

# 1. Define structured output schema i.e. defining what output you expect from your LLM.
#BaseModel comes from Pydantic
#Field() allows you to provide additional information about each field.
#sql_query: str Means the SQL query must be represented as a string.
class SQLGenerationOutput(BaseModel):
    sql_query: str = Field(
        description="The clean, executable SQL SELECT query. Do not wrap in markdown or backticks."
    )
#logic: str Means the explanation must also be a string.    
    logic: str = Field(
        description="The reasoning explaining which tables were joined or queried, which columns/filters were chosen, and why, based on the user's prompt."
    )

# 2. Initialize LangChain ChatOllama model and Parsers
#initializes the language model
llm = ChatOllama(
    model="qwen3:8b",
    temperature=0.0
)

#two parsers used because you have two different types of output

#Converts the model response into a normal string.Model output:Valid . Parser output:"VALID" . 
#You use this for your guardrail.
str_parser = StrOutputParser()

#It converts that JSON response from llm into a Python dictionary-like object.
#{
#    "sql_query": "SELECT * FROM customer",
#    "logic": "Retrieves all customer records."
#}

json_parser = JsonOutputParser(pydantic_object=SQLGenerationOutput)

# --- Guardrail Chain : decides whether a user question belongs to your banking database domain---
guardrail_prompt = ChatPromptTemplate.from_messages([
    ("system", "You are an input guardrail classifier for a banking database system."),
    ("human", """The database only contains tables and data for:
- Customers (CIF, Account number, Customer ID, Account status)
- Savings/Deposit accounts (Account scheme, savings details)
- Loan accounts (Loan schemes, personal or home loans)

Task:
Analyze the user's input.
- If the question asks for retrieving, summarizing, counting, filtering, or checking customer, loan, or account details, respond with EXACTLY: "VALID"
- If the question is general knowledge, math, chit-chat, coding, or unrelated, respond with EXACTLY: "INVALID"

User question: {user_query}""")
])

#creating guardrail chain - The pipe '|' connects components into a sequence first guardrail_prompt then llm and then str_parser
guardrail_chain = guardrail_prompt | llm | str_parser

# --- SQL Generation Chain with Explanation Logic ---
#LLM needs to understand the database structure before generating SQL, so we combine all three database schemas into one string
combined_schema = f"{schema_deposit}\n{schema_loan}\n{schema_customer}"

#llm for sql generation.here {schema} placeholder is replaced with combined_schema
#The LLM receives:1SQL engineer instructions.  2.Database schema  3.JSON formatting instructions  4.User's natural language question.
#it uses all 4 inputs to generate sql
sql_prompt = ChatPromptTemplate.from_messages([
    (
        "system",
        "You are an expert SQL engineer.\n"
        "Here is the database schema:\n{schema}\n\n"
        "{format_instructions}"
    ),
    (
        "human",
        "Convert the following natural language request into a valid SQL query and explain the underlying reasoning based on the request:\n{user_query}"
    )
]).partial(format_instructions=json_parser.get_format_instructions())
#json_parser.get_format_instructions()  :  Generates instructions based on your Pydantic schema i.e sql query plus logic of sql query. it tells the LLM to return a JSON object with the 2 fields.
#.partial() : This pre-fills the format_instructions variable in your prompt

#it creates a execution flow SQL Prompt i.e. Schema + user question + JSON instructions) -> llm model -> JsonOutputParser i.e. Extracts structured output {sql_query and logic}
sql_generation_chain = sql_prompt | llm | json_parser

#removes whitespaces, the text [```sql] and ENTER , ENTER and ['''$] from beginning of generated sql 
def clean_sql_output(raw_query: str) -> str:
    """Strip markdown code fence blocks if generated by LLM."""
    cleaned = re.sub(r"^```[a-zA-Z]*\n?", "", raw_query.strip())
    cleaned = re.sub(r"\n?```$", "", cleaned.strip())
    return cleaned.strip()

#validates/rejects the generated sql query
def is_safe_select_query(query: str) -> bool:
    """
    Validates that the SQL query is strictly a read-only SELECT query.
    Blocks multiple statements and disallowed DML/DDL commands.
    """
    #Remove whitespace and trailing semicolon
    cleaned = query.strip().rstrip(";").strip()

#semicolon inside query
    if ";" in cleaned:
        return False
    #If the query is empty, reject it.
    tokens = cleaned.split()
    if not tokens:
        return False
#allow only queries starting with SELECT or WITH
    first_token = tokens[0].upper()
    if first_token not in {"SELECT", "WITH"}:
        return False

#searches the SQL for disallowed keywords declared. if disallowed keyword exist in query then dont allow.
    upper_query = cleaned.upper()
    for keyword in DISALLOWED_KEYWORDS:
        if re.search(rf"\b{keyword}\b", upper_query):
            return False

    return True


def is_relevant_query(user_query: str) -> bool:
    """Invokes the LangChain guardrail chain to check query scope."""
    logger.info(f"Checking guardrail for user query: '{user_query}'")
    try:
        #pass user_query to guardrail_chain where it executes in a sequence > guardrail > llm > sql
        verdict = guardrail_chain.invoke({"user_query": user_query}).strip().upper()
        #This checks whether the word "VALID" exists inside the returned string.
        is_valid = "VALID" in verdict

        if is_valid:
            logger.info("Guardrail passed: VALID")
        else:
            logger.warning(f"Guardrail rejected query: INVALID (Raw output: {verdict})")

        return is_valid
    except Exception as e:
        logger.error(f"Error during guardrail verification via LangChain: {e}")
        return False

#this function Accepts the user's question and returns two strings as shown below.sql query and its explanation logic
def NLPtoSQl(query: str) -> Tuple[str, str]:
    """
    Invokes the LangChain SQL generation chain.
    Returns:
        tuple[str, str]: (sql_query, logic)
    """
    #Records that the application is starting SQL generation
    logger.info("Sending prompt to LangChain Ollama for SQL generation and logic explanation...")
    #sql gen chain i.e 
    try:
        result = sql_generation_chain.invoke({
            "schema": combined_schema,
            "user_query": query
        })
#result is a Python dictionary containing two values.
#result = {
 #   "sql_query": "```sql\nSELECT * FROM customer\n```",
 #  "logic": "Retrieves all customer records." }

#result.get("sql_query", "") extracts only the SQL query from the dictionary (not the sql logic explanation).
#clean_sql_output passes the extracted SQL query to your cleaning function
        sql_query = clean_sql_output(result.get("sql_query", ""))
        #This extracts the explanation generated by the LLM.If the logic field is missing, it returns:"No reasoning provided."
        logic = result.get("logic", "No reasoning provided.")

        logger.info(f"Generated SQL: {sql_query}")
        logger.info(f"Generated Logic: {logic}")

        return sql_query, logic

    except Exception as e:
        logger.error(f"Failed to generate SQL and logic via LangChain: {e}")
        raise